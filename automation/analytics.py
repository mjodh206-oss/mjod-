#!/usr/bin/env python3
"""Pull performance data and write a weekly scorecard for the kill/scale loop.

Read-only. Needs the YouTube Data API (statistics) and, for retention, the
YouTube Analytics API scope (yt-analytics.readonly). If retention data is
unavailable it degrades gracefully instead of failing the run.

Usage:
    python automation/analytics.py --days 28
    python automation/analytics.py --days 7 --no-write --json
Output: reports/YYYY-MM-DD.json and reports/latest.md (both gitignored)
"""
from __future__ import annotations

import argparse
import json
import sys
from datetime import date, timedelta
from typing import Any

from common import REPORT_DIR, analytics_api, channel_id, load_state, youtube

# Thresholds from docs/PLAYBOOK.md section 9
FLOOR_AVG_VIEW_PCT = 70.0
GOOD_AVG_VIEW_PCT = 85.0
FLOOR_COMMENTS_PER_1K = 3.0


def video_rows(yt: Any) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    ch = yt.channels().list(part="snippet,statistics", mine=True).execute()
    channel = ch["items"][0] if ch.get("items") else {}
    state = load_state("published")
    ids = [info["video_id"] for info in state.values()
           if isinstance(info, dict) and info.get("video_id")] if isinstance(state, dict) else []
    rows: list[dict[str, Any]] = []
    for i in range(0, len(ids), 50):
        resp = yt.videos().list(part="snippet,statistics", id=",".join(ids[i:i + 50])).execute()
        for item in resp.get("items", []):
            s = item.get("statistics", {})
            rows.append({
                "video_id": item["id"],
                "title": item["snippet"]["title"],
                "published_at": item["snippet"].get("publishedAt", ""),
                "views": int(s.get("viewCount", 0)),
                "likes": int(s.get("likeCount", 0)),
                "comments": int(s.get("commentCount", 0)),
            })
    return channel, rows


def retention(yt_analytics: Any, start: str, end: str) -> dict[str, dict[str, float]]:
    """video_id -> {avg_pct, avg_seconds} (best-effort)."""
    try:
        resp = yt_analytics.reports().query(
            ids="channel==MINE",
            startDate=start,
            endDate=end,
            metrics="views,averageViewDuration,averageViewPercentage,likes,comments,shares",
            dimensions="video",
            sort="-views",
            maxResults=50,
        ).execute()
    except Exception as exc:  # noqa: BLE001 - missing scope / no data must not kill the report
        print(f"! Retention metrics unavailable ({str(exc)[:160]})")
        return {}
    headers = [h["name"] for h in resp.get("columnHeaders", [])]
    out = {}
    for row in resp.get("rows", []):
        rec = dict(zip(headers, row))
        vid = rec.get("video")
        if not vid:
            continue
        out[vid] = {
            "avg_pct": float(rec.get("averageViewPercentage") or 0),
            "avg_seconds": float(rec.get("averageViewDuration") or 0),
            "shares": float(rec.get("shares") or 0),
        }
    return out


def verdict(row: dict[str, Any], ret: dict[str, float]) -> str:
    notes = []
    pct = ret.get("avg_pct", 0)
    if pct and pct < FLOOR_AVG_VIEW_PCT:
        notes.append("rewrite the hook / cut 5-8 s")
    elif pct >= GOOD_AVG_VIEW_PCT:
        notes.append("clone this pacing next week")
    views = max(row["views"], 1)
    cpm = row["comments"] / views * 1000
    if cpm < FLOOR_COMMENTS_PER_1K:
        notes.append("sharpen the binary CTA question")
    return "; ".join(notes) if notes else "keep — no action"


def build_report(channel: dict, rows: list[dict], ret: dict[str, dict[str, float]],
                 start: str, end: str) -> str:
    stats = channel.get("statistics", {})
    lines = [
        f"# Channel scorecard — {end}",
        "",
        f"Window: {start} → {end} · generated by `automation/analytics.py`",
        "",
        f"**Channel:** {channel.get('snippet', {}).get('title', '(unknown)')} · "
        f"subscribers {stats.get('subscriberCount', '?')} · "
        f"lifetime views {stats.get('viewCount', '?')} · videos {stats.get('videoCount', '?')}",
        "",
        "| Video | Views | Likes | Comments | C/1k | Avg % viewed | Action |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    for r in sorted(rows, key=lambda x: x["views"], reverse=True):
        m = ret.get(r["video_id"], {})
        pct = f"{m.get('avg_pct', 0):.0f}%" if m.get("avg_pct") else "n/a"
        cpm = r["comments"] / max(r["views"], 1) * 1000
        title = r["title"].replace("|", "\\|")[:58]
        lines.append(
            f"| [{title}](https://www.youtube.com/watch?v={r['video_id']}) | "
            f"{r['views']:,} | {r['likes']:,} | {r['comments']:,} | {cpm:.1f} | {pct} | "
            f"{verdict(r, m)} |"
        )
    if not rows:
        lines.append("| _(no published videos recorded in state/published.json yet)_ | — | — | — | — | — | — |")
    lines += [
        "",
        "## Sunday decisions",
        "",
        "- Top hook family this week: ______ (clone its *shape*, not the topic)",
        "- Worst hook family this week: ______ → retire for 2 weeks",
        "- CTA with the most comments: ______ → reuse its question shape",
        "- Next week's 5 topics: ______",
        "",
        "Targets: 3 s hold ≥ 65 % · avg % viewed ≥ 70 % · comments/1k ≥ 3 · loops ≥ 3 %.",
        "See `docs/PLAYBOOK.md` §9 for the full kill/scale rules.",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description="Build the weekly performance scorecard")
    ap.add_argument("--days", type=int, default=28, help="lookback window in days")
    ap.add_argument("--no-write", action="store_true", help="print only, don't touch reports/")
    ap.add_argument("--json", action="store_true", help="emit JSON instead of markdown")
    args = ap.parse_args()

    today = date.today()
    end = today.isoformat()
    start = (today - timedelta(days=args.days)).isoformat()
    print(f"Fetching {start} → {end} …")

    try:
        yt = youtube()
        channel_id(yt)  # validates credentials early
        channel, rows = video_rows(yt)
        ret = retention(analytics_api(), start, end)
    except SystemExit:
        raise
    except Exception as exc:  # noqa: BLE001
        print(f"ERROR: could not fetch analytics: {str(exc)[:300]}", file=sys.stderr)
        print("Check credentials/scopes: python automation/auth_setup.py", file=sys.stderr)
        return 2

    if args.json:
        print(json.dumps({"window": [start, end], "channel": channel.get("statistics", {}),
                          "videos": rows, "retention": ret}, indent=2))
        return 0

    report = build_report(channel, rows, ret, start, end)
    if not args.no_write:
        REPORT_DIR.mkdir(parents=True, exist_ok=True)
        (REPORT_DIR / f"{end}.json").write_text(
            json.dumps({"window": [start, end], "videos": rows, "retention": ret}, indent=2) + "\n",
            encoding="utf-8",
        )
        (REPORT_DIR / "latest.md").write_text(report, encoding="utf-8")
        print(f"✓ Wrote reports/latest.md and reports/{end}.json ({len(rows)} videos)")
    print()
    print(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
