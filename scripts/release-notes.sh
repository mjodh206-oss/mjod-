الإصدار الأول من **مجودة (Majwuda)** — مساعد ذكاء اصطناعي عربي يعمل بالصوت والنص، مدعوم بـ Claude.

## ما في هذا الإصدار
- محادثة نصية وصوتية متدفقة مع كشف اللغة العربية (محادثات، ملاحظات، تذكيرات، ذاكرة).
- شخصية مخصّصة، تفويض الأدوات (اتصال، رسائل، تقويم، جهاز، ملفات، بحث) مع تأكيد صريح للإجراءات الحساسة.
- تكاملات النظام: وضع المساعد الرقمي (ASSIST)، ودجت الشاشة الرئيسية، بلاطة الإعدادات السريعة، ومسارات صوتية وتذكيرات.
- واجهة عربية كاملة RTL مع خط IBM Plex Sans Arabic ووضع فاتح/داكن/حسب النظام.

## التثبيت
حمّل `majwuda-v1.0.0.apk` على جهاز أندرويد (Android 8.0+ مع التثبيت من مصادر خارجية مفعّل) ثبّته، ثم افتح مجودة وأدخل مفتاح Claude API من الإعدادات.

