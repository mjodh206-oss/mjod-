#!/usr/bin/env python3
"""Scaffold a new episode JSON with a correctly-scaled 8-beat timeline.

The generated file is a DRAFT: it contains TODO markers on purpose, so
`validate_content.py` / CI will fail until you actually write the script.

Usage:
    python tools/new_episode.py --id ep-006 --topic "why your voice sounds wrong on a recording" --series "Brain Glitches"
    python tools/new_episode.py --id ep-007 --topic "why octopus blood is blue" --series "Everyday Impossible" --duration 38
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

from validate_content import ROOT, EPISODE_DIR

BASE_BOUNDARIES = [0, 3, 8, 16, 22, 27, 37, 43, 45]
DEVICES = ["hook", "open loop", "mechanism / number", "pattern interrupt",
           "re-hook", "mechanism", "payoff", "loop / CTA"]
PROMPTS = [
    "TODO: hook, <= 12 words, spoken in the first 0.5 s",
    "TODO: open the loop — promise the payoff, don't deliver it",
    "TODO: first detail with a number or a visual",
    "TODO: pattern interrupt, new angle or sound hit",
    "TODO: re-hook — 'but that's not even the weird part'",
    "TODO: explain the actual mechanism, one idea only",
    "TODO: close the loop with the promised answer",
    "TODO: one binary question + final frame matches frame 1",
]


def scale(duration: int) -> list[int]:
    raw = [round(x * duration / 45) for x in BASE_BOUNDARIES]
    raw[0], raw[-1] = 0, duration
    for i in range(1, len(raw) - 1):
        if raw[i] <= raw[i - 1]:
            raw[i] = raw[i - 1] + 1
    raw[-2] = min(raw[-2], duration - 1)
    return raw


def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:40] or "episode"


def build(args: argparse.Namespace) -> dict[str, object]:
    boundaries = scale(args.duration)
    beats = []
    for i in range(len(boundaries) - 1):
        beats.append({
            "t": f"{boundaries[i]}-{boundaries[i + 1]}",
            "vo": PROMPTS[i],
            "on_screen": "TODO: 2-4 words",
            "visual": "TODO: what changes on screen",
            "device": DEVICES[i],
        })
    return {
        "id": args.id,
        "status": "draft",
        "series": args.series,
        "topic": args.topic,
        "format": "shorts",
        "duration_seconds": args.duration,
        "language": "en",
        "publish_at": None,
        "fact_check": {
            "claim": "TODO: the single claim the payoff depends on",
            "source_hint": "TODO: primary source to verify before publishing",
            "verified": False,
        },
        "hooks": [
            "TODO: contradiction hook, <= 12 words",
            "TODO: number or you-test hook, <= 12 words",
            "TODO: false-belief hook, <= 12 words",
        ],
        "selected_hook": 0,
        "titles": ["TODO: title 45-70 chars", "TODO: title variant B", "TODO: title variant C"],
        "beats": beats,
        "payoff": "TODO: the one sentence that closes the loop",
        "cta": "TODO: one binary question?",
        "pinned_comment": "TODO: channel's own low-effort question",
        "description": "TODO: hook restated, context, CTA, source hints.",
        "hashtags": ["#shorts", "#science", "#education"],
        "tags": ["education", "science", "shorts"],
        "thumbnail": {"text": "TODO 3 WORDS", "prompt": "TODO: art direction"},
        "video_file": None,
        "youtube_video_id": None,
        "notes": "Generated by tools/new_episode.py — replace every TODO before setting status to ready.",
    }


def main() -> int:
    ap = argparse.ArgumentParser(description="Scaffold a new Shorts episode")
    ap.add_argument("--id", required=True, help="ep-006, ep-007, ...")
    ap.add_argument("--topic", required=True)
    ap.add_argument("--series", default="Brain Glitches")
    ap.add_argument("--duration", type=int, default=45)
    ap.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = ap.parse_args()
    if not re.match(r"^ep-\d{3}$", args.id):
        print("ERROR: --id must look like ep-006", file=sys.stderr)
        return 2
    if not 20 <= args.duration <= 60:
        print("ERROR: --duration must be 20..60 seconds", file=sys.stderr)
        return 2
    path = EPISODE_DIR / f"{args.id}-{slug(args.topic)}.json"
    if path.exists() and not args.force:
        print(f"ERROR: {path.name} already exists (use --force)", file=sys.stderr)
        return 2
    path.write_text(json.dumps(build(args), indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Created {path.relative_to(ROOT)}")
    print(f"Timeline: {'-'.join(map(str, scale(args.duration)))}")
    print("Next: fill every TODO, verify the fact, set fact_check.verified=true, status=ready.")
    print("      python tools/validate_content.py   # will fail until the draft is finished (by design)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
