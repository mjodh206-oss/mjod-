# ---------------- معاينة: محلل مسارات مصغّر ----------------
def parse_path(d):
    toks = re.findall(r'[MLHVCSQZmlhvcsqz]|-?\d*\.?\d+', d)
    cmds, cur, i = [], [], 0
    cmd = None
    vals = []
    out = []
    idx = 0
    while idx < len(toks):
        t = toks[idx]
        if t.isalpha():
            if cmd is not None:
                out.append((cmd, vals))
            cmd, vals = t, []
        else:
            vals.append(float(t))
        idx += 1
    if cmd is not None:
        out.append((cmd, vals))
    # توسيع (مع قاعدة SVG: الإحداثيات الإضافية بعد M تصبح L)
    exp = []
    for c, v in out:
        n = {"M": 2, "L": 2, "H": 1, "V": 1, "C": 6, "S": 4, "Q": 4, "Z": 0}[c.upper()]
        if n == 0:
            exp.append((c, []))
            continue
        first = True
        for k in range(0, len(v), n):
            cc = c
            if not first and c.upper() == "M":
                cc = "L" if c == "M" else "l"
            exp.append((cc, v[k:k + n]))
            first = False
    return exp


def render_icon(els, size=96, pad=8):
    from PIL import ImageChops
    sc = (size - 2 * pad) / 24.0
    P = lambda x, y: (pad + x * sc, pad + y * sc)
    fill_mask = Image.new("1", (size, size), 0)
    stroke_img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    sd = ImageDraw.Draw(stroke_img)
    for el in els:
        cmds = parse_path(el[1])
        pts, cur, start = [], (0, 0), (0, 0)
        segs = []
        for c, v in cmds:
            if c == "M":
                if pts:
                    segs.append(pts)
                cur = (v[0], v[1]); start = cur; pts = [P(*cur)]
            elif c == "L":
                cur = (v[0], v[1]); pts.append(P(*cur))
            elif c == "H":
                cur = (v[0], cur[1]); pts.append(P(*cur))
            elif c == "V":
                cur = (cur[0], v[0]); pts.append(P(*cur))
            elif c == "C":
                p0, p1, p2, p3 = cur, (v[0], v[1]), (v[2], v[3]), (v[4], v[5])
                for i in range(1, 17):
                    t = i / 16; u = 1 - t
                    x = u**3*p0[0] + 3*u*u*t*p1[0] + 3*u*t*t*p2[0] + t**3*p3[0]
                    y = u**3*p0[1] + 3*u*u*t*p1[1] + 3*u*t*t*p2[1] + t**3*p3[1]
                    pts.append(P(x, y))
                cur = p3
            elif c == "Q":
                p0, p1, p2 = cur, (v[0], v[1]), (v[2], v[3])
                for i in range(1, 17):
                    t = i / 16; u = 1 - t
                    x = u*u*p0[0] + 2*u*t*p1[0] + t*t*p2[0]
                    y = u*u*p0[1] + 2*u*t*p1[1] + t*t*p2[1]
                    pts.append(P(x, y))
                cur = p2
            elif c == "Z":
                pts.append(P(*start)); cur = start
        if pts:
            segs.append(pts)
        for seg in segs:
            if len(seg) < 2:
                continue
            if el[0] == "f":
                m = Image.new("1", (size, size), 0)
                ImageDraw.Draw(m).polygon(seg, fill=1)
                fill_mask = ImageChops.logical_xor(fill_mask, m)
            else:
                sd.line(seg, fill=(20, 40, 44, 255), width=max(2, int(el[2] * sc * 0.9)), joint="curve")
    alpha = fill_mask.convert("L").point(lambda v: 255 if v else 0)
    rgb = Image.new("RGBA", (size, size), (20, 40, 44, 255))
    img = Image.composite(rgb, Image.new("RGBA", (size, size), (0, 0, 0, 0)), alpha)
    img = Image.alpha_composite(img, stroke_img)
    return img


